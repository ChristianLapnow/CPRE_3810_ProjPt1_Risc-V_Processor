-------------------------------------------------------------------------
-- fullAdder.vhd
-------------------------------------------------------------------------
-- DESCRIPTION: This file contains an implementation of a 1-bit full
-- adder using structural VHDL, built from the provided xorg2.vhd,
-- andg2.vhd, and org2.vhd gate designs.
--
-- o_S    = i_A XOR i_B XOR i_Cin
-- o_Cout = (i_A AND i_B) OR (i_Cin AND (i_A XOR i_B))
--
-- The first XOR result is reused by both the sum path and the carry
-- path, so the whole cell needs only five two-input gates.
-------------------------------------------------------------------------

library IEEE;
use IEEE.std_logic_1164.all;

entity fullAdder is
  port(i_A          : in  std_logic;
       i_B          : in  std_logic;
       i_Cin        : in  std_logic;
       o_S          : out std_logic;
       o_Cout       : out std_logic);
end fullAdder;

architecture structural of fullAdder is

  component xorg2 is
    port(i_A        : in  std_logic;
         i_B        : in  std_logic;
         o_F        : out std_logic);
  end component;

  component andg2 is
    port(i_A        : in  std_logic;
         i_B        : in  std_logic;
         o_F        : out std_logic);
  end component;

  component org2 is
    port(i_A        : in  std_logic;
         i_B        : in  std_logic;
         o_F        : out std_logic);
  end component;

  signal s_AxorB  : std_logic;  -- i_A XOR i_B, used by both outputs
  signal s_AandB  : std_logic;  -- carry generated by A and B together
  signal s_CandX  : std_logic;  -- carry propagated through from i_Cin

begin

  -- Sum path: XOR the two operands, then XOR in the carry.
  g_Xor1 : xorg2
    port map(i_A => i_A,
             i_B => i_B,
             o_F => s_AxorB);

  g_Xor2 : xorg2
    port map(i_A => s_AxorB,
             i_B => i_Cin,
             o_F => o_S);

  -- Carry path: a carry is generated when both operands are 1 ...
  g_And1 : andg2
    port map(i_A => i_A,
             i_B => i_B,
             o_F => s_AandB);

  -- ... or propagated when exactly one operand is 1 and a carry came in.
  g_And2 : andg2
    port map(i_A => s_AxorB,
             i_B => i_Cin,
             o_F => s_CandX);

  g_Or1 : org2
    port map(i_A => s_AandB,
             i_B => s_CandX,
             o_F => o_Cout);

end structural;